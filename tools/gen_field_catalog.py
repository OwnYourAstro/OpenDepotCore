"""Generate src/model/field_catalog.cpp from the codeplug schemas."""

import argparse
import json
from pathlib import Path


def cstr(value):
    if value is None:
        return "nullptr"
    value = str(value)
    value = value.replace("\\", "\\\\").replace('"', '\\"')
    value = value.replace("\n", "\\n").replace("\r", "")
    return f'"{value}"'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--fields", type=Path, required=True)
    parser.add_argument("--tables", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()

    fields = json.loads(args.fields.read_text(encoding="utf-8"))
    tables = json.loads(args.tables.read_text(encoding="utf-8"))
    fields.sort(key=lambda row: int(row["fid"]))

    lines = [
        "// SPDX-FileCopyrightText: 2026 Sarah Rose",
        "// SPDX-License-Identifier: MIT",
        "// Generated by tools/gen_field_catalog.py. Do not edit.",
        "",
        '#include "opendepot/core/field_catalog.h"',
        "",
        "#include <string>",
        "",
        "namespace opendepot {",
        "namespace {",
        "const FieldDef kFields[] = {",
    ]
    for row in fields:
        lines.append(
            f'    {{{int(row["fid"])}, {cstr(row.get("name"))}, {cstr(row.get("g"))}, '
            f'{int(row["off"])}, {int(row["bits"])}, {int(row["msb"])}, '
            f'{int(row.get("block_id") if row.get("block_id") is not None else -1)}, '
            f'{cstr(row.get("table_key"))}, {cstr(row.get("record_tag"))}}},'
        )
    lines += [
        "};",
        "const size_t kFieldCount = sizeof(kFields) / sizeof(kFields[0]);",
        "",
    ]

    table_refs = []
    for table_index, table in enumerate(tables["tables"]):
        bindings = []
        columns = []
        binding_index = 0
        for column in table["columns"]:
            start = binding_index
            for bind in column.get("bindings", []):
                bindings.append(
                    f'    {{{int(bind["fid"])}, {cstr(bind["group"])}, '
                    f'{int(bind["off"])}, {int(bind["bits"])}, {int(bind["msb"])}, '
                    f'{int(bind.get("block_id") if bind.get("block_id") is not None else -1)}}},'
                )
                binding_index += 1
            pointer = f"kBindings_{table_index} + {start}" if binding_index > start else "nullptr"
            columns.append(
                f'    {{{int(column["index"])}, {cstr(column["name"])}, '
                f'{cstr(column.get("match"))}, {pointer}, {binding_index - start}}},'
            )
        lines.append(f"const FieldBinding kBindings_{table_index}[] = {{")
        lines.extend(bindings or ["    {0, nullptr, 0, 0, 0, -1},"])
        lines.append("};")
        lines.append(f"const TableColumnDef kColumns_{table_index}[] = {{")
        lines.extend(columns or ["    {0, \"\", \"missing\", kBindings_0, 0, 0},"])
        lines.append("};")
        table_refs.append(
            f'    {{{cstr(table["key"])}, {cstr(table["title"])}, '
            f'{cstr(table.get("core_section"))}, kColumns_{table_index}, '
            f'{len(table["columns"])}, {int(table["bound_column_count"])}}},'
        )

    lines += [
        "const TableDef kTables[] = {",
        *table_refs,
        "};",
        "const size_t kTableCount = sizeof(kTables) / sizeof(kTables[0]);",
        "}  // namespace",
        "",
        "const FieldDef* FieldCatalog(size_t& count) {",
        "    count = kFieldCount;",
        "    return kFields;",
        "}",
        "",
        "const FieldDef* FindField(uint16_t fid) {",
        "    size_t lo = 0, hi = kFieldCount;",
        "    while (lo < hi) {",
        "        const size_t mid = lo + (hi - lo) / 2;",
        "        if (kFields[mid].fid < fid) lo = mid + 1;",
        "        else hi = mid;",
        "    }",
        "    return (lo < kFieldCount && kFields[lo].fid == fid) ? &kFields[lo] : nullptr;",
        "}",
        "",
        "const TableDef* TableCatalog(size_t& count) {",
        "    count = kTableCount;",
        "    return kTables;",
        "}",
        "",
        "const TableDef* FindTable(const char* key) {",
        "    if (!key) return nullptr;",
        "    for (size_t i = 0; i < kTableCount; ++i) {",
        "        if (kTables[i].key && std::string(kTables[i].key) == key) return &kTables[i];",
        "    }",
        "    return nullptr;",
        "}",
        "",
        "uint64_t ReadFieldBits(const uint8_t* data, size_t size, uint16_t off,",
        "                       uint16_t bits, uint8_t msb) {",
        "    if (!data || bits == 0) return 0;",
        "    const size_t pos = size_t(off) * 8 + (7 - msb);",
        "    if (pos + bits > size * 8) return 0;",
        "    uint64_t value = 0;",
        "    for (uint16_t i = 0; i < bits; ++i) {",
        "        const size_t bit = pos + i;",
        "        value = (value << 1) | ((data[bit / 8] >> (7 - (bit % 8))) & 1);",
        "    }",
        "    return value;",
        "}",
        "",
        "}  // namespace opendepot",
        "",
    ]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {args.out}: {len(fields)} fields, {len(tables['tables'])} tables")


if __name__ == "__main__":
    raise SystemExit(main())
